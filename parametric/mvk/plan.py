"""
mvk.plan - floors built from a drawn plan instead of generated by rules.

A plan file (Marievik+/data/plans/<project>/<building>.json) describes a building as it stands:
a local frame fitted to the footprint, the column grid, cores (stair + lifts), the atrium, the
facade, and per floor type the partitions with their doors and the named rooms. See the file's
_meta for its source. floor_from_plan() turns one plan floor into the same Floor object that
layout_floor() produces, so quantities, pricing, rooms, units and the 3D view all work unchanged.

Wall categories as in layout.py: E facade, K core and columns (retained), S atrium edge,
P partitions (space plan: what a change of use moves).
"""
import json
import math

from shapely.geometry import Polygon, box
from shapely.geometry.polygon import orient
from shapely.ops import unary_union

try:
    from . import layout as L
except ImportError:  # loaded outside the package
    import layout as L


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def floor_for(plan, index):
    """The plan floor drawn for this floor index, or None."""
    for key, fl in plan["floors"].items():
        at = fl.get("applies_to")
        if (isinstance(at, list) and index in at) or (isinstance(at, str) and at.endswith("+") and index >= int(at[:-1])):
            return dict(fl, key=key)
    return None


class Frame(object):
    """Local plan coordinates (x along the street, y inward) to site coordinates."""

    def __init__(self, plan):
        f = plan["frame"]
        self.o = f["origin"]
        ux, uy = f["x_axis"]
        n = math.hypot(ux, uy)
        self.u = (ux / n, uy / n)
        self.v = (-self.u[1], self.u[0])
        self.size = f["size_m"]

    def pt(self, p):
        x, y = p
        return (self.o[0] + self.u[0] * x + self.v[0] * y, self.o[1] + self.u[1] * x + self.v[1] * y)

    def rect(self, r):
        x0, y0, x1, y1 = r
        return Polygon([self.pt((x0, y0)), self.pt((x1, y0)), self.pt((x1, y1)), self.pt((x0, y1))])


def floor_from_plan(plan, pf, footprint, use, profiles, db, index=0, z=0.0, height=3.5):
    prof = profiles[use]
    fr = Frame(plan)
    P0 = orient(footprint, 1.0)
    F = L.Floor(index, z, height, use, prof, db, P0)
    fac = plan["facade"]
    wall = F.wall

    def inner(cat, a, b, wtype):
        """An interior wall whose room-boundary axis overshoots both ends a little, so rooms close
        where it meets another wall or the facade (the overshoot is dropped when rooms are found)."""
        (ux, uy), _ = L._unit(a, b)
        return wall(cat, a, b, wtype=wtype, axis=(L._add(a, (ux, uy), -0.3), L._add(b, (ux, uy), 0.3)))
    F.wall = lambda cat, a, b, axis=None, wtype=None: inner(cat, a, b, wtype) if cat != "E" and axis is None else wall(cat, a, b, axis, wtype)
    t_ext = db[fac["type"]]["thickness_m"]

    # ---- facade: one wall per footprint edge, glazed as drawn
    for a, b in L._segs(L._rings(L._mbuf(P0, -t_ext / 2))[0]):
        F.wall("E", a, b, wtype=fac["type"])

    # ---- columns on the perimeter grid (retained structure), drawn as short thick K walls
    g = plan["grid"]
    c, W, D = g["column_m"], fr.size[0], fr.size[1]
    pts = {(x, y) for x in g["x"] for y in (g["y"][0], g["y"][-1])} | {(x, y) for y in g["y"] for x in (g["x"][0], g["x"][-1])}
    for x, y in sorted(pts):
        cx, cy = min(max(x, c / 2), W - c / 2), min(max(y, c / 2), D - c / 2)
        a, b = fr.pt((cx - c / 2, cy)), fr.pt((cx + c / 2, cy))
        F.wall("K", a, b, axis=(a, b), wtype=g["column_type"])

    # ---- cores: stair and lift shafts in concrete, doors on the drawn side
    door = lambda t: (db[t]["width_m"] or 0.9, db[t]["height_m"] or 2.1)
    for core in plan["cores"]:
        x0, y0, x1, y1 = core["rect"]
        F.zones.append(("Core", fr.rect(core["rect"])))
        sides = {"west": ((x0, y0), (x0, y1)), "east": ((x1, y0), (x1, y1)),
                 "south": ((x0, y0), (x1, y0)), "north": ((x0, y1), (x1, y1))}
        door_side = core.get("door_side", "west")
        for name, (a, b) in sides.items():
            w = F.wall("K", fr.pt(a), fr.pt(b), wtype=plan["core_type"])
            if name != door_side:
                continue
            sy0, sy1 = core["stair"][1], core["stair"][3]
            dw, dh = door("D_FIRE_EI60_1000")
            F.opening("door", w, (sy0 + sy1) / 2 - y0, dw, 0.0, dh, "D_FIRE_EI60_1000")
            n = core.get("lifts", 0)
            sh = (core["stair"][1] - y0) / max(n, 1)
            for i in range(n):
                F.opening("door", w, sh * (i + 0.5), 1.0, 0.0, 2.1, "D_INT_GLASS_1000")
        sx0, sy0, sx1, sy1 = core["stair"]
        F.wall("K", fr.pt((x0, sy0)), fr.pt((x1, sy0)), wtype=plan["core_type"])
        n = core.get("lifts", 0)
        for i in range(1, n):
            yy = y0 + (sy0 - y0) * i / n
            F.wall("K", fr.pt((x0, yy)), fr.pt((x1, yy)), wtype=plan["core_type"])

    # ---- atrium: a void with a glass edge above the ground floor, a glazed garden court on it
    ar = plan["atrium"]["rect"]
    poly = fr.rect(ar)
    if pf.get("atrium") == "void":
        F.voids.append(poly)
        F.zones.append(("Atrium (void)", poly))
    x0, y0, x1, y1 = ar
    for k, (a, b) in enumerate((((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0)))):
        w = F.wall("S", fr.pt(a), fr.pt(b), wtype="IW_GLASS_PARTITION")
        if pf.get("atrium") == "garden" and k == 0:
            F.opening("door", w, (x1 - x0) / 2, 1.0, 0.0, 2.1, "D_INT_GLASS_1000")

    # ---- partitions and their doors (the space plan)
    for wd in pf.get("walls", []):
        w = F.wall("P", fr.pt(wd["a"]), fr.pt(wd["b"]), wtype=wd["type"])
        dt = "D_INT_GLASS_1000" if wd["type"] == "IW_GLASS_PARTITION" else "D_INT_SINGLE_900"
        for d in wd.get("doors", []):
            dw, dh = door(d.get("type", dt))
            F.opening("door", w, d["at"], dw, 0.0, dh, d.get("type", dt))

    # ---- rooms: drawn rectangles; an "open" room is what is left once the others are taken out
    closed = [(r["name"], fr.rect(r["rect"])) for r in pf.get("rooms", []) if not r.get("open")]
    taken = unary_union([p for _, p in closed] + [z for _, z in F.zones])
    for name, p in closed:
        F.zones.append((name, p))
    for r in pf.get("rooms", []):
        if r.get("open"):
            for p in L._polys(fr.rect(r["rect"]).difference(taken), 2.0):
                F.zones.append((r["name"], p))

    # ---- entrances, then the curtain-wall glazing on every facade wall
    ext = [w for w in F.walls if w["cat"] == "E"]
    for e in pf.get("entrances", []):
        local = {"south": (e["at"], 0.0), "north": (e["at"], D), "west": (0.0, e["at"]), "east": (W, e["at"])}[e["side"]]
        p = fr.pt(local)
        w = min(ext, key=lambda w: L.LineString([w["a"], w["b"]]).distance(L.Point(p)))
        uu, _ = L._unit(w["a"], w["b"])
        s = (p[0] - w["a"][0]) * uu[0] + (p[1] - w["a"][1]) * uu[1]
        dw, dh = door(e["type"])
        F.opening("door", w, s, dw, 0.0, dh, e["type"])
    head = F.wall_h - fac.get("head_below_ceiling", 0.2)
    for w in ext:
        L.place_windows(F, w, wwr=fac["wwr"], module=fac["module"], wtype=fac["window_type"], sill=fac["sill"], head=head)
    del F.wall                     # back to the class method for anything added later (overrides)
    return F
